import fs from "fs";
import path from "path";
import sample from "@/data/spotify.sample.json";

export type SpotifyItem = {
  name: string;
  artists?: string[];
  image: string | null;
  url: string | null;
};

export type NowPlaying = {
  isPlaying: boolean;
  track: string | null;
  artists: string[];
  albumArt: string | null;
  url: string | null;
  playedAt: string | null;
};

export type SpotifyData = {
  source: "spotify" | "sample";
  fetchedAt: string;
  topTracks: SpotifyItem[];
  topArtists: SpotifyItem[];
  topAlbums: SpotifyItem[];
  lastPlayed: Omit<NowPlaying, "isPlaying"> | null;
};

let cached: SpotifyData | null = null;

/**
 * Build-time Spotify snapshot. spotify.json is generated by scripts/fetch-spotify.mjs
 * (and gitignored), so fall back to the committed sample when it isn't there.
 */
export function getSpotifyData(): SpotifyData {
  if (cached) return cached;
  const generated = path.join(process.cwd(), "src/data/spotify.json");
  try {
    cached = JSON.parse(fs.readFileSync(generated, "utf8")) as SpotifyData;
  } catch {
    cached = sample as SpotifyData;
  }
  return cached;
}
